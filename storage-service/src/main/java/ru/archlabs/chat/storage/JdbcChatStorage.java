package ru.archlabs.chat.storage;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Objects;
import java.util.Optional;

import org.h2.jdbcx.JdbcDataSource;

import ru.archlabs.chat.domain.ChatNotFoundException;
import ru.archlabs.chat.domain.ChatUser;
import ru.archlabs.chat.domain.ChatValidationException;
import ru.archlabs.chat.domain.Message;
import ru.archlabs.chat.domain.Notification;

/**
 * Embedded H2 storage. Every operation uses its own short-lived connection, so the
 * server can be stopped and restarted without losing committed data.
 */
public final class JdbcChatStorage implements ChatStorage {
    private static final String AT = "at";
    private static final String USER_SELECT =
            "SELECT name, online, notifications_enabled, last_seen ";
    private static final String SENDER_COLUMN = "sender";
    private static final String BODY_COLUMN = "body";
    private static final String INSERT_NOTIFICATION =
            "INSERT INTO notifications(recipient, message_id, sender, body, message_created_at, "
                    + "created_at) VALUES (?, ?, ?, ?, ?, ?)";

    private final JdbcDataSource dataSource;
    private final int shardIndex;
    private final int shardCount;

    public JdbcChatStorage(String jdbcUrl) {
        this(jdbcUrl, 0, 1);
    }

    public JdbcChatStorage(String jdbcUrl, int shardIndex, int shardCount) {
        Objects.requireNonNull(jdbcUrl, "jdbcUrl");
        if (shardCount < 1 || shardIndex < 0 || shardIndex >= shardCount) {
            throw new IllegalArgumentException("Invalid shard index/count");
        }
        this.shardIndex = shardIndex;
        this.shardCount = shardCount;
        dataSource = new JdbcDataSource();
        dataSource.setURL(jdbcUrl);
        dataSource.setUser("sa");
        dataSource.setPassword("");
    }

    @Override
    public void initialize() {
        String identity =
                "(START WITH " + (shardIndex + 1L) + " INCREMENT BY " + shardCount + ")";
        try (Connection connection = open();
                Statement statement = connection.createStatement()) {
            statement.execute(
                    """
                    CREATE TABLE IF NOT EXISTS users (
                        name VARCHAR(64) PRIMARY KEY,
                        online BOOLEAN NOT NULL,
                        notifications_enabled BOOLEAN NOT NULL,
                        last_seen BIGINT NOT NULL
                    )
                    """);
            statement.execute(
                    """
                    CREATE TABLE IF NOT EXISTS messages (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY %s PRIMARY KEY,
                        sender VARCHAR(64) NOT NULL,
                        body VARCHAR(4000) NOT NULL,
                        created_at BIGINT NOT NULL
                    )
                    """
                            .formatted(identity));
            statement.execute(
                    """
                    CREATE TABLE IF NOT EXISTS notifications (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY %s PRIMARY KEY,
                        recipient VARCHAR(64) NOT NULL,
                        message_id BIGINT NOT NULL,
                        sender VARCHAR(64) NOT NULL,
                        body VARCHAR(4000) NOT NULL,
                        message_created_at BIGINT NOT NULL,
                        created_at BIGINT NOT NULL,
                        delivered_at BIGINT
                    )
                    """
                            .formatted(identity));
            statement.execute(
                    "CREATE INDEX IF NOT EXISTS idx_notifications_pending "
                            + "ON notifications(recipient, delivered_at)");
        } catch (SQLException exception) {
            throw new StorageException("Cannot initialize H2 storage", exception);
        }
        migrateNotifications();
    }

    @Override
    public void connect(String name, Instant at) {
        String user = requireName(name);
        Objects.requireNonNull(at, AT);
        try (Connection connection = open();
                PreparedStatement update =
                        connection.prepareStatement(
                                "UPDATE users SET online = TRUE, last_seen = ? WHERE name = ?")) {
            update.setLong(1, at.toEpochMilli());
            update.setString(2, user);
            if (update.executeUpdate() == 0) {
                try (PreparedStatement insert =
                        connection.prepareStatement(
                                """
                                INSERT INTO users(name, online, notifications_enabled, last_seen)
                                VALUES (?, TRUE, TRUE, ?)
                                """)) {
                    insert.setString(1, user);
                    insert.setLong(2, at.toEpochMilli());
                    insert.executeUpdate();
                }
            }
        } catch (SQLException exception) {
            throw new StorageException("Cannot connect user " + user, exception);
        }
    }

    @Override
    public void disconnect(String name, Instant at) {
        String user = requireName(name);
        Objects.requireNonNull(at, AT);
        try (Connection connection = open();
                PreparedStatement statement =
                        connection.prepareStatement(
                                "UPDATE users SET online = FALSE, last_seen = ? WHERE name = ?")) {
            statement.setLong(1, at.toEpochMilli());
            statement.setString(2, user);
            statement.executeUpdate();
        } catch (SQLException exception) {
            throw new StorageException("Cannot disconnect user " + user, exception);
        }
    }

    @Override
    public void setNotificationsEnabled(String name, boolean enabled) {
        String user = requireName(name);
        try (Connection connection = open();
                PreparedStatement statement =
                        connection.prepareStatement(
                                "UPDATE users SET notifications_enabled = ? WHERE name = ?")) {
            statement.setBoolean(1, enabled);
            statement.setString(2, user);
            if (statement.executeUpdate() == 0) {
                throw new ChatNotFoundException("Unknown user: " + user);
            }
        } catch (SQLException exception) {
            throw new StorageException("Cannot update user " + user, exception);
        }
    }

    @Override
    public Optional<ChatUser> findUser(String name) {
        String user = requireName(name);
        try (Connection connection = open();
                PreparedStatement statement =
                        connection.prepareStatement(
                                USER_SELECT
                                        + "FROM users WHERE name = ?")) {
            statement.setString(1, user);
            try (ResultSet result = statement.executeQuery()) {
                if (!result.next()) {
                    return Optional.empty();
                }
                return Optional.of(readUser(result));
            }
        } catch (SQLException exception) {
            throw new StorageException("Cannot read user " + user, exception);
        }
    }

    @Override
    public List<ChatUser> allUsers() {
        try (Connection connection = open();
                Statement statement = connection.createStatement();
                ResultSet result =
                        statement.executeQuery(
                                USER_SELECT
                                        + "FROM users ORDER BY name")) {
            ArrayList<ChatUser> users = new ArrayList<ChatUser>();
            while (result.next()) {
                users.add(readUser(result));
            }
            return List.copyOf(users);
        } catch (SQLException exception) {
            throw new StorageException("Cannot read users", exception);
        }
    }

    @Override
    public Message appendMessage(
            String sender, String text, List<String> notificationRecipients, Instant at) {
        String author = requireName(sender);
        String body = requireText(text, "Message");
        Objects.requireNonNull(notificationRecipients, "notificationRecipients");
        Objects.requireNonNull(at, AT);
        try (Connection connection = open()) {
            connection.setAutoCommit(false);
            try {
                Message message = insertMessage(connection, author, body, at);
                insertNotifications(connection, message, notificationRecipients, at);
                connection.commit();
                return message;
            } catch (SQLException | RuntimeException exception) {
                connection.rollback();
                throw exception;
            }
        } catch (SQLException exception) {
            throw new StorageException("Cannot append message", exception);
        }
    }

    @Override
    public List<Message> history(int limit) {
        if (limit <= 0) {
            throw new ChatValidationException("History limit must be positive");
        }
        try (Connection connection = open();
                PreparedStatement statement =
                        connection.prepareStatement(
                                "SELECT id, sender, body, created_at FROM messages "
                                        + "ORDER BY id DESC LIMIT ?")) {
            statement.setInt(1, limit);
            try (ResultSet result = statement.executeQuery()) {
                ArrayList<Message> messages = new ArrayList<Message>();
                while (result.next()) {
                    messages.add(readMessage(result, "id", SENDER_COLUMN, BODY_COLUMN, "created_at"));
                }
                Collections.reverse(messages);
                return List.copyOf(messages);
            }
        } catch (SQLException exception) {
            throw new StorageException("Cannot read history", exception);
        }
    }

    @Override
    public Notification enqueueNotification(String recipient, Message message, Instant at) {
        String target = requireName(recipient);
        Objects.requireNonNull(message, "message");
        Objects.requireNonNull(at, AT);
        try (Connection connection = open()) {
            return insertNotification(connection, target, message, at);
        } catch (SQLException exception) {
            throw new StorageException("Cannot enqueue notification", exception);
        }
    }

    @Override
    public List<Notification> pendingNotifications(String recipient) {
        String target = requireName(recipient);
        try (Connection connection = open();
                PreparedStatement statement =
                        connection.prepareStatement(
                                """
                                SELECT id AS notification_id, recipient, message_id, sender, body,
                                       message_created_at, created_at AS notified_at
                                FROM notifications
                                WHERE recipient = ? AND delivered_at IS NULL
                                ORDER BY id
                                """)) {
            statement.setString(1, target);
            try (ResultSet result = statement.executeQuery()) {
                ArrayList<Notification> pending = new ArrayList<Notification>();
                while (result.next()) {
                    Message message =
                            new Message(
                                    result.getLong("message_id"),
                                    result.getString(SENDER_COLUMN),
                                    result.getString(BODY_COLUMN),
                                    Instant.ofEpochMilli(result.getLong("message_created_at")));
                    pending.add(
                            new Notification(
                                    result.getLong("notification_id"),
                                    result.getString("recipient"),
                                    message,
                                    Instant.ofEpochMilli(result.getLong("notified_at"))));
                }
                return List.copyOf(pending);
            }
        } catch (SQLException exception) {
            throw new StorageException("Cannot read pending notifications", exception);
        }
    }

    @Override
    public void markNotificationDelivered(long notificationId, Instant at) {
        Objects.requireNonNull(at, AT);
        try (Connection connection = open();
                PreparedStatement statement =
                        connection.prepareStatement(
                                "UPDATE notifications SET delivered_at = ? "
                                        + "WHERE id = ? AND delivered_at IS NULL")) {
            statement.setLong(1, at.toEpochMilli());
            statement.setLong(2, notificationId);
            statement.executeUpdate();
        } catch (SQLException exception) {
            throw new StorageException("Cannot mark notification delivered", exception);
        }
    }

    @Override
    public void resetOnlineUsers() {
        try (Connection connection = open();
                Statement statement = connection.createStatement()) {
            statement.executeUpdate("UPDATE users SET online = FALSE");
        } catch (SQLException exception) {
            throw new StorageException("Cannot reset online users", exception);
        }
    }

    private void migrateNotifications() {
        try (Connection connection = open();
                Statement statement = connection.createStatement()) {
            statement.execute(
                    "ALTER TABLE notifications DROP CONSTRAINT IF EXISTS fk_notifications_message");
            statement.execute(
                    "ALTER TABLE notifications ADD COLUMN IF NOT EXISTS sender VARCHAR(64)");
            statement.execute(
                    "ALTER TABLE notifications ADD COLUMN IF NOT EXISTS body VARCHAR(4000)");
            statement.execute(
                    "ALTER TABLE notifications ADD COLUMN IF NOT EXISTS message_created_at BIGINT");
            statement.execute(
                    """
                    UPDATE notifications n SET
                        sender = COALESCE(n.sender,
                            (SELECT m.sender FROM messages m WHERE m.id = n.message_id)),
                        body = COALESCE(n.body,
                            (SELECT m.body FROM messages m WHERE m.id = n.message_id)),
                        message_created_at = COALESCE(n.message_created_at,
                            (SELECT m.created_at FROM messages m WHERE m.id = n.message_id))
                    """);
            statement.execute("ALTER TABLE notifications ALTER COLUMN sender SET NOT NULL");
            statement.execute("ALTER TABLE notifications ALTER COLUMN body SET NOT NULL");
            statement.execute(
                    "ALTER TABLE notifications ALTER COLUMN message_created_at SET NOT NULL");
        } catch (SQLException exception) {
            throw new StorageException("Cannot migrate notification storage", exception);
        }
    }

    private Message insertMessage(
            Connection connection, String sender, String text, Instant at) throws SQLException {
        try (PreparedStatement statement =
                connection.prepareStatement(
                        "INSERT INTO messages(sender, body, created_at) VALUES (?, ?, ?)",
                        Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, sender);
            statement.setString(2, text);
            statement.setLong(3, at.toEpochMilli());
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (!keys.next()) {
                    throw new SQLException("H2 did not return a message id");
                }
                return new Message(keys.getLong(1), sender, text, at);
            }
        }
    }

    private void insertNotifications(
            Connection connection,
            Message message,
            List<String> recipients,
            Instant at)
            throws SQLException {
        LinkedHashSet<String> unique = new LinkedHashSet<String>();
        for (String recipient : recipients) {
            unique.add(requireName(recipient));
        }
        if (unique.isEmpty()) {
            return;
        }
        try (PreparedStatement statement =
                connection.prepareStatement(
                        INSERT_NOTIFICATION)) {
            for (String recipient : unique) {
                bindNotification(statement, recipient, message, at);
                statement.addBatch();
            }
            statement.executeBatch();
        }
    }

    private Notification insertNotification(
            Connection connection, String recipient, Message message, Instant at)
            throws SQLException {
        try (PreparedStatement statement =
                connection.prepareStatement(
                        INSERT_NOTIFICATION,
                        Statement.RETURN_GENERATED_KEYS)) {
            bindNotification(statement, recipient, message, at);
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (!keys.next()) {
                    throw new SQLException("H2 did not return a notification id");
                }
                return new Notification(keys.getLong(1), recipient, message, at);
            }
        }
    }

    private static void bindNotification(
            PreparedStatement statement, String recipient, Message message, Instant at)
            throws SQLException {
        statement.setString(1, recipient);
        statement.setLong(2, message.id());
        statement.setString(3, message.sender());
        statement.setString(4, message.text());
        statement.setLong(5, message.createdAt().toEpochMilli());
        statement.setLong(6, at.toEpochMilli());
    }

    private static ChatUser readUser(ResultSet result) throws SQLException {
        return new ChatUser(
                result.getString("name"),
                result.getBoolean("online"),
                result.getBoolean("notifications_enabled"),
                Instant.ofEpochMilli(result.getLong("last_seen")));
    }

    private static Message readMessage(
            ResultSet result, String id, String sender, String body, String createdAt)
            throws SQLException {
        return new Message(
                result.getLong(id),
                result.getString(sender),
                result.getString(body),
                Instant.ofEpochMilli(result.getLong(createdAt)));
    }

    private Connection open() throws SQLException {
        return dataSource.getConnection();
    }

    private static String requireName(String value) {
        if (value == null || value.isBlank()) {
            throw new ChatValidationException("Username must not be blank");
        }
        return value.strip();
    }

    private static String requireText(String value, String label) {
        if (value == null || value.isBlank()) {
            throw new ChatValidationException(label + " must not be blank");
        }
        return value.strip();
    }
}
